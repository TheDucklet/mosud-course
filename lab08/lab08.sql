-- справочник складов: ID, код, название, город, штат, ZIP, признак активности
CREATE TABLE lab.warehouses (
    warehouse_id integer GENERATED BY DEFAULT AS IDENTITY,
    warehouse_code varchar(12) NOT NULL,
    warehouse_name varchar(60) NOT NULL,
    city varchar(80) NOT NULL,
    state char(2) NOT NULL,
    zip_code_prefix integer,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_warehouses PRIMARY KEY (warehouse_id),
    CONSTRAINT uq_warehouses_code UNIQUE (warehouse_code),
    CONSTRAINT uq_warehouses_city_name UNIQUE (city, warehouse_name),
    CONSTRAINT ck_warehouses_state CHECK (state ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_warehouses_zip CHECK (zip_code_prefix BETWEEN 1000 AND 99999)
);

-- остатки товара по складам: составной ключ склад+товар, FK на olist.products
CREATE TABLE lab.warehouse_inventory (
    warehouse_id integer NOT NULL,
    product_id text NOT NULL,
    qty_on_hand integer NOT NULL DEFAULT 0,
    reserved_qty integer NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_warehouse_inventory PRIMARY KEY (warehouse_id, product_id),
    CONSTRAINT fk_warehouse_inventory_warehouse FOREIGN KEY (warehouse_id) REFERENCES lab.warehouses (warehouse_id) ON DELETE RESTRICT,
    CONSTRAINT fk_warehouse_inventory_product FOREIGN KEY (product_id) REFERENCES olist.products (product_id) ON DELETE RESTRICT,
    CONSTRAINT ck_warehouse_inventory_qty_on_hand CHECK (qty_on_hand >= 0),
    CONSTRAINT ck_warehouse_inventory_reserved CHECK (reserved_qty >= 0 AND reserved_qty <= qty_on_hand)
);

-- шапка перемещения: склад-источник, склад-назначение, даты и статус
CREATE TABLE lab.warehouse_transfers (
    transfer_id integer GENERATED BY DEFAULT AS IDENTITY,
    transfer_no varchar(20) NOT NULL,
    source_warehouse_id integer NOT NULL,
    destination_warehouse_id integer NOT NULL,
    status varchar(12) NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    shipped_at timestamptz,
    received_at timestamptz,
    CONSTRAINT pk_warehouse_transfers PRIMARY KEY (transfer_id),
    CONSTRAINT uq_warehouse_transfers_no UNIQUE (transfer_no),
    CONSTRAINT fk_warehouse_transfers_source FOREIGN KEY (source_warehouse_id) REFERENCES lab.warehouses (warehouse_id) ON DELETE RESTRICT,
    CONSTRAINT fk_warehouse_transfers_destination FOREIGN KEY (destination_warehouse_id) REFERENCES lab.warehouses (warehouse_id) ON DELETE RESTRICT,
    CONSTRAINT ck_warehouse_transfers_distinct CHECK (source_warehouse_id <> destination_warehouse_id),
    CONSTRAINT ck_warehouse_transfers_status CHECK (status IN ('draft', 'shipped', 'received', 'cancelled')),
    CONSTRAINT ck_warehouse_transfers_order_dates CHECK (shipped_at IS NULL OR received_at IS NULL OR received_at >= shipped_at)
);

-- позиции перемещения: составной ключ transfer+product, FK на olist.products
CREATE TABLE lab.warehouse_transfer_items (
    transfer_id integer NOT NULL,
    product_id text NOT NULL,
    qty integer NOT NULL,
    note varchar(120),
    CONSTRAINT pk_warehouse_transfer_items PRIMARY KEY (transfer_id, product_id),
    CONSTRAINT fk_warehouse_transfer_items_transfer FOREIGN KEY (transfer_id) REFERENCES lab.warehouse_transfers (transfer_id) ON DELETE CASCADE,
    CONSTRAINT fk_warehouse_transfer_items_product FOREIGN KEY (product_id) REFERENCES olist.products (product_id) ON DELETE RESTRICT,
    CONSTRAINT ck_warehouse_transfer_items_qty CHECK (qty > 0)
);

-- склады: 5 строк, города взяты из реальных городов продавцов Olist
INSERT INTO lab.warehouses (warehouse_code, warehouse_name, city, state, zip_code_prefix)
SELECT v.code, v.name, s.seller_city, s.seller_state, s.seller_zip_code_prefix
FROM (VALUES
        ('WH-SP01', 'СПб-Главный',   'sao paulo'),
        ('WH-SP02', 'СПб-Юг',        'sao paulo'),
        ('WH-RJ01', 'Рио-Склад',     'rio de janeiro'),
        ('WH-CWB1', 'Куритиба',      'curitiba'),
        ('WH-POA1', 'Порту-Алегри',  'porto alegre')
     ) AS v (code, name, city)
CROSS JOIN LATERAL (
    SELECT c.seller_city, c.seller_state, c.seller_zip_code_prefix
    FROM olist.sellers AS c
    WHERE c.seller_city = v.city
    ORDER BY c.seller_id
    LIMIT 1
) AS s;

-- остатки: по товару из самых продаваемых категорий на каждый склад
INSERT INTO lab.warehouse_inventory (warehouse_id, product_id, qty_on_hand, reserved_qty)
SELECT w.warehouse_id, p.product_id, 10 + (w.warehouse_id * 7) % 40, (w.warehouse_id * 7) % 40 / 4
FROM lab.warehouses AS w
JOIN LATERAL (
    SELECT oi.product_id
    FROM olist.order_items AS oi
    JOIN olist.products AS p2 ON p2.product_id = oi.product_id
    WHERE p2.product_category_name = 'beleza_saude'
    GROUP BY oi.product_id
    ORDER BY count(*) DESC, oi.product_id
    OFFSET (w.warehouse_id - 1) * 3
    LIMIT 3
) AS p ON true;

-- перемещения: 5 строк на реальные даты заказов Olist с тем же смещением по дням
INSERT INTO lab.warehouse_transfers (transfer_no, source_warehouse_id, destination_warehouse_id, status, created_at, shipped_at, received_at)
SELECT
    'TR-' || lpad(v.n::text, 4, '0'),
    (SELECT warehouse_id FROM lab.warehouses WHERE warehouse_code = v.src),
    (SELECT warehouse_id FROM lab.warehouses WHERE warehouse_code = v.dst),
    v.status,
    d.purchase_ts + make_interval(hours => v.h_created),
    d.purchase_ts + make_interval(hours => v.h_created + 24),
    CASE WHEN v.h_received IS NULL THEN NULL
         ELSE d.purchase_ts + make_interval(hours => v.h_created + v.h_received) END
FROM (VALUES
        (1, 'WH-SP01', 'WH-SP02', 'received',  0, 48),
        (2, 'WH-SP01', 'WH-CWB1', 'received',  6, 72),
        (3, 'WH-RJ01', 'WH-POA1', 'shipped',   9, NULL),
        (4, 'WH-SP02', 'WH-RJ01', 'draft',    12, NULL),
        (5, 'WH-POA1', 'WH-SP02', 'cancelled', 15, NULL),
        (6, 'WH-CWB1', 'WH-SP01', 'draft',    18, NULL)
     ) AS v (n, src, dst, status, h_created, h_received)
CROSS JOIN LATERAL (
    SELECT o.order_purchase_timestamp AS purchase_ts
    FROM olist.orders AS o
    WHERE o.order_purchase_timestamp IS NOT NULL
    ORDER BY o.order_id
    OFFSET v.n - 1
    LIMIT 1
) AS d;

-- позиции перемещений: по две позиции на перемещение из остатков склада-источника
INSERT INTO lab.warehouse_transfer_items (transfer_id, product_id, qty, note)
SELECT t.transfer_id, r.product_id, r.pos_no + 1,
       'позиция ' || (r.pos_no + 1)::text || ' перемещения ' || t.transfer_no
FROM lab.warehouse_transfers AS t
JOIN LATERAL (
    SELECT i2.product_id, (row_number() OVER (ORDER BY i2.product_id))::int - 1 AS pos_no
    FROM lab.warehouse_inventory AS i2
    WHERE i2.warehouse_id = t.source_warehouse_id
    ORDER BY i2.product_id
    LIMIT 2
) AS r ON true;

-- проверка 1: все ограничения новых таблиц из pg_constraint с их определениями
SELECT c.relname AS table_name,
       con.conname AS constraint_name,
       CASE con.contype WHEN 'p' THEN 'PRIMARY KEY' WHEN 'f' THEN 'FOREIGN KEY'
                        WHEN 'u' THEN 'UNIQUE' WHEN 'c' THEN 'CHECK' ELSE con.contype::text END AS kind,
       pg_get_constraintdef(con.oid) AS definition
FROM pg_constraint AS con
JOIN pg_class AS c ON c.oid = con.conrelid
JOIN pg_namespace AS n ON n.oid = c.relnamespace
WHERE n.nspname = 'lab'
  AND c.relname IN ('warehouses', 'warehouse_inventory', 'warehouse_transfers', 'warehouse_transfer_items')
ORDER BY c.relname, split_part(con.conname, '_', 1), con.conname;

-- проверка 2: сколько ограничений каждого вида в схеме lab
SELECT CASE con.contype WHEN 'p' THEN 'PK' WHEN 'f' THEN 'FK' WHEN 'u' THEN 'UNIQUE' WHEN 'c' THEN 'CHECK' END AS kind,
       count(*) AS cnt
FROM pg_constraint AS con
JOIN pg_class AS c ON c.oid = con.conrelid
JOIN pg_namespace AS n ON n.oid = c.relnamespace
WHERE n.nspname = 'lab'
  AND c.relname IN ('warehouses', 'warehouse_inventory', 'warehouse_transfers', 'warehouse_transfer_items')
GROUP BY con.contype
ORDER BY 1;

-- проверка 3: NOT NULL-столбцы новых таблиц с полными именами
SELECT n.nspname || '.' || c.relname AS table_name,
       a.attname AS column_name,
       format_type(a.atttypid, a.atttypmod) AS data_type
FROM pg_attribute AS a
JOIN pg_class AS c ON c.oid = a.attrelid
JOIN pg_namespace AS n ON n.oid = c.relnamespace
WHERE n.nspname = 'lab'
  AND c.relname IN ('warehouses', 'warehouse_inventory', 'warehouse_transfers', 'warehouse_transfer_items')
  AND a.attnum > 0
  AND NOT a.attisdropped
  AND a.attnotnull
ORDER BY table_name, a.attnum;

-- проверка 4: внешние ключи на olist и локальные, таблица ссылается -> что
SELECT n.nspname || '.' || c.relname AS from_table,
       con.conname AS fk_name,
       fn.nspname || '.' || fc.relname || '(' || pg_get_constraintdef(con.oid) || ')' AS target
FROM pg_constraint AS con
JOIN pg_class AS c ON c.oid = con.conrelid
JOIN pg_namespace AS n ON n.oid = c.relnamespace
JOIN pg_class AS fc ON fc.oid = con.confrelid
JOIN pg_namespace AS fn ON fn.oid = fc.relnamespace
WHERE con.contype = 'f'
  AND n.nspname = 'lab'
  AND c.relname IN ('warehouses', 'warehouse_inventory', 'warehouse_transfers', 'warehouse_transfer_items')
ORDER BY fc.relnamespace = (SELECT oid FROM pg_namespace WHERE nspname = 'olist') DESC, con.conname;

-- проверка 5: число строк в новых таблицах
SELECT 'lab.warehouses' AS table_name, count(*) AS rows FROM lab.warehouses
UNION ALL SELECT 'lab.warehouse_inventory', count(*) FROM lab.warehouse_inventory
UNION ALL SELECT 'lab.warehouse_transfers', count(*) FROM lab.warehouse_transfers
UNION ALL SELECT 'lab.warehouse_transfer_items', count(*) FROM lab.warehouse_transfer_items
ORDER BY 1;

-- проверка 6: эталонный отчёт «перемещение — источник — назначение — сумма qty»
SELECT t.transfer_no, ws.city AS source_city, wd.city AS destination_city,
       count(*) AS positions, sum(ti.qty) AS total_qty
FROM lab.warehouse_transfers AS t
JOIN lab.warehouses AS ws ON ws.warehouse_id = t.source_warehouse_id
JOIN lab.warehouses AS wd ON wd.warehouse_id = t.destination_warehouse_id
JOIN lab.warehouse_transfer_items AS ti ON ti.transfer_id = t.transfer_id
GROUP BY t.transfer_no, ws.city, wd.city
ORDER BY t.transfer_no;

-- проверка 7: все product_id позиций реально существуют в olist.products
SELECT count(*) AS items, count(p.product_id) AS matched_in_olist
FROM lab.warehouse_transfer_items AS ti
LEFT JOIN olist.products AS p ON p.product_id = ti.product_id;

-- демонстрация: UPDATE склада активным — остатки и перемещения по нему
SELECT w.warehouse_code, count(DISTINCT i.product_id) AS inventory_rows, count(DISTINCT t.transfer_id) AS transfers_out
FROM lab.warehouses AS w
LEFT JOIN lab.warehouse_inventory AS i ON i.warehouse_id = w.warehouse_id
LEFT JOIN lab.warehouse_transfers AS t ON t.source_warehouse_id = w.warehouse_id
GROUP BY w.warehouse_code
ORDER BY w.warehouse_code;

